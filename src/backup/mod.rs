//! Бэкапы: упаковка сервера, хранение архивов и восстановление из них.
//!
//! Бэкап бывает двух видов. Полный `.tar.gz` — самодостаточный архив; так
//! снимались все бэкапы до инкрементальных, и так снимаются, если они
//! выключены в конфиге. Снимок — манифест в хранилище кусков сервера
//! (`repo.rs`): куски общие для всех снимков, и мир, поменявшийся за день на
//! проценты, добавляет на диск проценты, а не ещё одну копию себя.
//!
//! Архив лежит на самой ноде — там, где уже лежат байты. Заливка в хранилище
//! (S3, WebDAV) идёт оттуда же и напрямую, минуя мастер: гонять терабайтный
//! мир через него незачем.

