//! Бэкапы: упаковка рядом с сервером и восстановление из архива.
//!
//! Архив лежит на самой ноде — там, где уже лежат байты. Заливка в хранилище
//! (S3, WebDAV) идёт оттуда же и напрямую, минуя мастер: гонять терабайтный
//! мир через него незачем.

pub mod create;
pub mod remote;
pub mod restore;

use std::path::{Path, PathBuf};

/// Где хранится архив. Внутри служебного каталога сервера: так он не попадает
/// ни в файловый менеджер, ни в синк сборки, ни в следующий бэкап.
pub fn archive_path(root: &Path, backup: uuid::Uuid) -> PathBuf {
    root.join(".noro")
        .join("backups")
        .join(format!("{backup}.tar.gz"))
}
